export const REPO_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../../..");

export type AgentRunOptions = {
  repo: string;
  base: string;
  app: string;
  branch?: string;
  maxRepairs?: number;
  scenarios?: number[];
  approvePlan?: (plan: FilePlan, repoMap: RepoMap) => Promise<boolean>;
  log?: (msg: string) => void;
};

export type Attempt = {
  iteration: number;
  commitSha: string;
  checks: CheckResult[];
  harnessRunId?: string;
  harnessStatus?: string;
  scenarioTable?: string;
  failingCheck: string | null;
  errorSummary: string | null;
  repair?: FinishReport;
};

export type AgentReport = {
  runId: string;
  status: "passed" | "failed" | "plan_rejected" | "error";
  model: string;
  repo: string;
  app: string;
  base: string;
  baseSha: string;
  branch: string;
  headSha?: string;
  commits: { sha: string; message: string }[];
  repoMap?: RepoMap;
  plan?: FilePlan;
  implementation?: FinishReport;
  attempts: Attempt[];
  apimaticQueries: ApimaticContext["queries"];
  usage: Usage;
  estimatedCostUsd: number;
  couldNotVerify: string[];
  startedAt: string;
  finishedAt?: string;
  error?: string;
};

/**
 * The repo's .env.local wins over an inherited ANTHROPIC_API_KEY (dotenv never
 * overrides variables that are already set, and shells often carry other keys).
 */
export function anthropicApiKey(): string | undefined {
  const file = path.join(REPO_ROOT, ".env.local");
  const fromFile = existsSync(file) ? parseEnv(readFileSync(file, "utf8")).ANTHROPIC_API_KEY : undefined;
  return fromFile || process.env.ANTHROPIC_API_KEY;
}

// claude-opus-5-5 list prices per million tokens.
const PRICE = { input: 4, output: 20, cacheRead: 0.2, cacheWrite: 5 };
const cost = (u: Usage) =>
  Math.round(((u.inputTokens * PRICE.input + u.outputTokens * PRICE.output + u.cacheReadTokens * PRICE.cacheRead + u.cacheWriteTokens * PRICE.cacheWrite) / 1e6) * 100) / 100;

const STAGE_ORDER = ["dependencies", "database", "server", "client", "config"] as const;
const STAGE_MESSAGES: Record<string, string> = {
  dependencies: "PayPal: add the PayPal server SDK",
  database: "PayPal: add payment provider fields to orders (migration)",
  server: "PayPal: server routes for client token, orders, capture, webhooks, and refunds",
  client: "PayPal: PayPal button and Pay Later messaging at checkout",
  config: "PayPal: document PayPal environment variables",
};
const TRAILER = `\n\nGenerated by Second Button (${MODEL}).`;

function finishTool<T>(name: string, description: string, schema: Parameters<typeof defineTool>[2], onFinish?: (v: T) => string | null): AgentTool {
  return defineTool(name, description, schema, async (input) => {
    const problem = onFinish?.(input as T);
    if (problem) throw new Error(problem);
    return { finish: input, message: "Recorded." };
  });
}

export async function runAgent(opts: AgentRunOptions): Promise<AgentReport> {
  const log = opts.log ?? ((m: string) => console.log(m));
  const maxRepairs = opts.maxRepairs ?? 4;
  const runId = new Date().toISOString().replace(/[:.]/g, "-").replace("T", "_").slice(0, 19);
  const outDir = path.join(REPO_ROOT, "agent-runs", runId);
  mkdirSync(outDir, { recursive: true });
  const branch = opts.branch ?? `second-button/add-paypal-${runId}`;
  const worktreeDir = path.join(opts.repo, ".worktrees", `agent-${runId}`);
  const appPrefix = opts.app.replace(/\\/g, "/").replace(/\/$/, "") || ".";
  const toRepoPath = (rel: string) => (appPrefix === "." ? rel : `${appPrefix}/${rel}`);

  const usage = emptyUsage();
  const apimatic = new ApimaticContext();
  const report: AgentReport = {
    runId,
    status: "error",
    model: MODEL,
    repo: opts.repo,
    app: appPrefix,
    base: opts.base,
    baseSha: "",
    branch,
    commits: [],
    attempts: [],
    apimaticQueries: apimatic.queries,
    usage,
    estimatedCostUsd: 0,
    couldNotVerify: [],
    startedAt: new Date().toISOString(),
  };
  const save = () => {
    report.estimatedCostUsd = cost(usage);
    writeFileSync(path.join(outDir, "report.json"), JSON.stringify(report, null, 2));
  };

  try {
    log(`Agent run ${runId}: ${opts.repo} @ ${opts.base} (${appPrefix}) → ${branch}`);
    report.baseSha = createWorktree(opts.repo, opts.base, branch, worktreeDir);
    const appDir = path.join(worktreeDir, appPrefix);
    const commandEnv = { DATABASE_URL: "file:./prisma/agent.db", NEXT_TELEMETRY_DISABLED: "1" };

    log("  setup: install and migrate a scratch database");
    for (const [name, cmd] of [
      ["install", "pnpm install --frozen-lockfile"],
      ["migrate", "pnpm exec prisma migrate deploy"],
      ["generate", "pnpm exec prisma generate"],
    ]) {
      const step = runStep(name, cmd, appDir, commandEnv);
      if (!step.pass) throw new Error(`Setup step "${name}" failed:\n${step.output}`);
    }

    const client = new Anthropic({ apiKey: anthropicApiKey() });
    const ws: Workspace = { appDir, apimatic, policy: { mode: "readonly" }, written: new Set(), commandEnv };
    const loop = (stage: string, prompt: string, tools: AgentTool[], maxTurns: number) => {
      log(`▶ ${stage}`);
      return runLoop({ client, system: SYSTEM_PROMPT, prompt, tools, maxTurns, transcriptFile: path.join(outDir, `transcript-${stage}.jsonl`), usage, log });
    };

    /* Stage 1: analyze */
    const analyzed = await loop("analyze", analyzePrompt(appPrefix), [
      ...readTools(ws),
      finishTool("submit_repo_map", "Submit the repository map. Call this once when the analysis is complete.", RepoMapSchema),
    ], 40);
    if (!analyzed.finished) throw new Error(`Analysis did not finish (${analyzed.stopReason})`);
    const repoMap = RepoMapSchema.parse(analyzed.finished);
    report.repoMap = repoMap;
    writeFileSync(path.join(outDir, "repo-map.json"), JSON.stringify(repoMap, null, 2));
    log(`  repo map: ${repoMap.stripeFiles.length} Stripe files, order model ${repoMap.orderModel.prismaModel}`);
    save();

    /* Stage 2: plan */
    const repoMapJson = JSON.stringify(repoMap, null, 2);
    const stripeSet = new Set(repoMap.stripeFiles.map((f) => f.replace(/\\/g, "/")));
    const planned = await loop("plan", planPrompt(repoMapJson), [
      ...readTools(ws),
      finishTool<FilePlan>("submit_plan", "Submit the file plan. Call this once when the plan is complete.", FilePlanSchema, (p) => {
        const bad = p.files.filter((f) => stripeSet.has(f.path));
        return bad.length ? `The plan includes Stripe files, which must never be modified: ${bad.map((f) => f.path).join(", ")}` : null;
      }),
    ], 30);
    if (!planned.finished) throw new Error(`Planning did not finish (${planned.stopReason})`);
    const plan = FilePlanSchema.parse(planned.finished);
    report.plan = plan;
    writeFileSync(path.join(outDir, "plan.json"), JSON.stringify(plan, null, 2));
    log(`  plan: ${plan.files.length} files`);
    save();

    if (opts.approvePlan && !(await opts.approvePlan(plan, repoMap))) {
      report.status = "plan_rejected";
      return report;
    }

    /* Stage 3: implement */
    const planPaths = plan.files.map((f) => f.path.replace(/\\/g, "/"));
    ws.policy = { mode: "plan", writable: new Set(planPaths), protectedFiles: stripeSet };
    const planJson = JSON.stringify(plan, null, 2);
    const implemented = await loop("implement", implementPrompt(repoMapJson, planJson), [
      ...readTools(ws),
      ...writeTools(ws),
      finishTool("finish_implementation", "Call when the implementation builds cleanly.", FinishSchema),
    ], 90);
    if (implemented.finished) {
      report.implementation = FinishSchema.parse(implemented.finished);
    } else {
      log(`  implementation stopped without finishing (${implemented.stopReason}); checking what was written`);
    }

    // One commit per stage, in a fixed order.
    const changed = changedFiles(worktreeDir, report.baseSha, appPrefix);
    const stageOf = (f: string) =>
      plan.files.find((p) => p.path === f)?.stage ?? (["package.json", "pnpm-lock.yaml", "pnpm-workspace.yaml"].includes(f) ? "dependencies" : "config");
    for (const stage of STAGE_ORDER) {
      const files = changed.filter((f) => stageOf(f) === stage).map(toRepoPath);
      const sha = commitPaths(worktreeDir, files, STAGE_MESSAGES[stage] + TRAILER);
      if (sha) report.commits.push({ sha, message: STAGE_MESSAGES[stage] });
    }
    save();

    /* Check → harness → repair */
    const knownSecrets = ["PAYPAL_CLIENT_SECRET", "PAYPAL_CLIENT_ID", "STRIPE_SECRET_KEY", "PAYPAL_SANDBOX_BUYER_PASSWORD", "ANTHROPIC_API_KEY"]
      .map((k) => process.env[k] ?? "")
      .filter(Boolean);

    for (let iteration = 0; iteration <= maxRepairs; iteration++) {
      const commitSha = git(worktreeDir, ["rev-parse", "HEAD"]);
      log(`▶ check attempt ${iteration} @ ${commitSha.slice(0, 8)}`);
      const attempt: Attempt = { iteration, commitSha, checks: [], failingCheck: null, errorSummary: null };
      report.attempts.push(attempt);

      attempt.checks = buildChecks(appDir, commandEnv);
      if (attempt.checks.every((c) => c.pass)) {
        const files = changedFiles(worktreeDir, report.baseSha, appPrefix);
        const diff = diffSince(worktreeDir, report.baseSha, appPrefix);
        attempt.checks.push(
          sdkMethodGuard(appDir, files),
          planScopeGuard(files, planPaths),
          stripeGuard(files, [...stripeSet]),
          secretsGuard(diff, knownSecrets),
        );
      }
      for (const c of attempt.checks) log(`   ${c.pass ? "✓" : "✗"} ${c.name}${c.pass ? "" : `: ${c.output.split("\n").slice(-3).join(" ").slice(0, 200)}`}`);

      const failed = attempt.checks.find((c) => !c.pass);
      let harness: RunReport | null = null;
      if (failed) {
        attempt.failingCheck = failed.name;
        attempt.errorSummary = failed.output.slice(-1500);
      } else {
        harness = await runHarness({ repo: opts.repo, ref: branch, app: appPrefix, scenarios: opts.scenarios, log: (m) => log(`   │ ${m}`) });
        attempt.harnessRunId = harness.runId;
        attempt.harnessStatus = harness.status;
        attempt.scenarioTable = formatTable(harness);
        const failing = harness.scenarios.filter((s) => s.status === "fail");
        if (harness.status === "passed") {
          report.couldNotVerify = harness.couldNotVerify;
        } else {
          attempt.failingCheck = failing.length ? failing.map((s) => `scenario ${s.id} (${s.name})`).join(", ") : "harness run";
          attempt.errorSummary = harness.error ?? failing.map((s) => `${s.id}: ${s.error ?? s.checks.filter((c) => !c.pass).map((c) => c.name).join("; ")}`).join("\n");
        }
      }
      const attemptDir = path.join(outDir, `attempt-${iteration}`);
      mkdirSync(attemptDir, { recursive: true });
      writeFileSync(path.join(attemptDir, "diff.patch"), diffSince(worktreeDir, report.baseSha, appPrefix));
      writeFileSync(path.join(attemptDir, "attempt.json"), JSON.stringify(attempt, null, 2));
      save();

      if (!attempt.failingCheck) {
        report.status = "passed";
        log(`✓ passed on attempt ${iteration}`);
        break;
      }
      if (iteration === maxRepairs) {
        report.status = "failed";
        report.couldNotVerify.push(`Still failing after ${maxRepairs} repair rounds: ${attempt.failingCheck}`);
        break;
      }

      /* Repair */
      const evidence = buildEvidence(failed ?? null, harness);
      writeFileSync(path.join(attemptDir, "evidence.md"), evidence);
      const repaired = await loop(`repair-${iteration + 1}`, repairPrompt({ round: iteration + 1, maxRounds: maxRepairs, planJson, evidence }), [
        ...readTools(ws),
        ...writeTools(ws),
        finishTool("finish_repair", "Call when the fix is in place and the project builds.", FinishSchema),
      ], 50);
      if (repaired.finished) attempt.repair = FinishSchema.parse(repaired.finished);
      const files = changedFiles(worktreeDir, report.baseSha, appPrefix).map(toRepoPath);
      const msg = `PayPal: repair round ${iteration + 1} (${attempt.failingCheck})`;
      const sha = commitPaths(worktreeDir, files, msg + (attempt.repair ? `\n\n${attempt.repair.summary}` : "") + TRAILER);
      if (sha) report.commits.push({ sha, message: msg });
    }
    report.headSha = git(worktreeDir, ["rev-parse", "HEAD"]);
  } catch (err) {
    report.status = "error";
    report.error = (err as Error).message;
    log(`✗ ${report.error}`);
  } finally {
    report.finishedAt = new Date().toISOString();
    save();
    try {
      rmSync(worktreeDir, { recursive: true, force: true, maxRetries: 10, retryDelay: 500 });
      git(opts.repo, ["worktree", "prune"]);
    } catch {
      /* leave it for inspection */
    }
  }
  return report;
}

/** Turns a failing check or harness run into the exact evidence the repair stage sees. */
function buildEvidence(failedCheck: CheckResult | null, harness: RunReport | null): string {
  if (failedCheck) return `## Failing check: ${failedCheck.name}\n\n\`\`\`\n${failedCheck.output}\n\`\`\``;
  if (!harness) return "No evidence.";
  const parts = [`## Harness run ${harness.runId}: ${harness.status}`, "", formatTable(harness)];
  if (harness.error) parts.push("", `Run error: ${harness.error}`);
  for (const s of harness.scenarios.filter((x) => x.status === "fail")) {
    parts.push("", `### Scenario ${s.id}: ${s.name}`);
    if (s.error) parts.push(`Error: ${s.error}`);
    for (const c of s.checks) parts.push(`- ${c.pass ? "PASS" : "FAIL"} ${c.name}${c.detail ? `: ${c.detail.slice(0, 600)}` : ""}`);
    if (s.notes.length) parts.push(`Notes: ${s.notes.join("; ")}`);
    if (s.apiEvidence) parts.push("PayPal/Stripe API evidence:", "```json", JSON.stringify(s.apiEvidence, null, 2).slice(0, 3000), "```");
  }
  const storeLog = path.join(REPO_ROOT, "runs", harness.runId, "store.log");
  if (existsSync(storeLog)) {
    const text = readFileSync(storeLog, "utf8");
    // The last "▲ Next.js" banner is `next start`; everything after it is the running server's output.
    const serverPart = text.slice(Math.max(0, text.lastIndexOf("▲ Next.js")));
    parts.push("", "## Store server log (tail)", "```", serverPart.slice(-5000), "```");
  }
  return parts.join("\n");
}
